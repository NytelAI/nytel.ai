#!/usr/bin/env python3
"""Render the site's static files from templates/*.j2 and _data/messaging.yaml.

_data/messaging.yaml is a STRIPPED copy of NytelAI/knowledge-base marketing/messaging.yaml
(the master). It carries only copy: no comments, *source* fields, status_note, claim_note,
note or usage. Refresh it from a knowledge-base checkout, then build:

    pip install jinja2 pyyaml
    python3 build.py --sync ../knowledge-base/marketing/messaging.yaml   # strip + copy the master
    python3 build.py                  # writes index.html, _footer.html, llms.txt
    quarto render whitepaper.qmd      # only if whitepaper.qmd or _footer.html changed

GitHub Pages serves the committed output as-is, so commit the rendered files too.
"""
import argparse
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "_data" / "messaging.yaml"
OUTPUTS = {
    "index.html.j2": "index.html",
    "_footer.html.j2": "_footer.html",
    "llms.txt.j2": "llms.txt",
}
INTERNAL_KEYS = {"status_note", "claim_note", "note", "usage"}
PRIVATE_TOP = {"offer", "event"}  # event-specific (ARPA-H SURPASS) copy stays out of the public site


def strip_internal(node):
    """Drop internal fields: any key containing 'source', plus INTERNAL_KEYS."""
    if isinstance(node, dict):
        return {k: strip_internal(v) for k, v in node.items()
                if "source" not in k and k not in INTERNAL_KEYS}
    if isinstance(node, list):
        return [strip_internal(v) for v in node]
    return node


def sync(master: Path) -> None:
    data = strip_internal(yaml.safe_load(master.read_text(encoding="utf-8")))
    data = {k: v for k, v in data.items() if k not in PRIVATE_TOP}
    header = ("# Generated by build.py --sync from NytelAI/knowledge-base marketing/messaging.yaml.\n"
              "# Public copy only. Do not edit here; edit the master and re-sync.\n")
    DATA.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000),
                    encoding="utf-8")
    print(f"wrote {DATA.relative_to(ROOT)} (stripped)")


def resolve(root, dotted):
    for k in dotted.split("."):
        root = root[k]
    return root


def build() -> None:
    m = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    caps = m["capabilities"]
    groups = {"items": caps["items"], "mvp_agents": caps["mvp_agents"]["items"]}
    built = [groups[r["group"]][r["index"]] for r in caps["built_rows"]]
    site_points = [resolve(m, p["ref"])[p["index"]][p["field"]] for p in m["how_it_works"]["site_points"]]

    env = Environment(
        loader=FileSystemLoader(ROOT / "templates"),
        autoescape=select_autoescape(enabled_extensions=("html", "html.j2")),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
    )
    for src, dst in OUTPUTS.items():
        out = env.get_template(src).render(**m, m=m, built=built, site_points=site_points)
        (ROOT / dst).write_text(out, encoding="utf-8")
        print(f"wrote {dst}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sync", metavar="MASTER_YAML", type=Path,
                    help="strip internal fields from the knowledge-base master and write _data/messaging.yaml first")
    args = ap.parse_args()
    if args.sync:
        sync(args.sync)
    build()
